<?php

declare(strict_types=1);

namespace Sillbeam\Core\Tests\Unit;

use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use Sillbeam\Core\Architecture\Console\ArchitectureRenderer;
use Symfony\Component\Console\Helper\Helper;
use Symfony\Component\Console\Output\BufferedOutput;

require_once __DIR__.'/../Fixtures/CliPrototype12/src/Scenarios.php';
require_once __DIR__.'/../Fixtures/CliPrototype12/src/ArchitectureRenderer.php';

final class ArchitectureRendererTest extends TestCase
{
    /** @return iterable<string, array{string, bool, int|null}> */
    public static function goldens(): iterable
    {
        foreach (['success', 'conflict', 'multiple'] as $scenario) {
            yield $scenario.'-default' => [$scenario, false, null];
            yield $scenario.'-all' => [$scenario, true, null];
        }
        yield 'multiple-focus2' => ['multiple', false, 2];
    }

    #[DataProvider('goldens')]
    public function testExactOriginalTxtAndMarkupGoldens(string $name, bool $all, ?int $issue): void
    {
        $id = $name.($all ? '-all' : (null !== $issue ? '-focus'.$issue : '-default'));
        $scenario = \SillbeamPrototype\Scenarios::get($name);
        $reference = __DIR__.'/../Fixtures/CliPrototype12/previews/'.$id;
        $txt = file_get_contents($reference.'.txt');
        self::assertIsString($txt);
        $markup = json_decode((string) file_get_contents($reference.'.markup.json'), true, flags: \JSON_THROW_ON_ERROR);
        // Original goldens were generated by a stand-in that doubles backslashes.
        // Actual Symfony's formatter does not; decode only that documented transport difference.
        $markup = array_map(static fn (string $line): string => str_replace('\\\\', '\\', $line), $markup);
        foreach ([false, true] as $ansi) {
            $expected = new BufferedOutput(decorated: $ansi);
            $expected->writeln($markup);
            $output = new BufferedOutput(decorated: $ansi);
            (new ArchitectureRenderer($output, 84, false, $all, $issue))->render($scenario);
            $actual = $output->fetch();
            self::assertSame($expected->fetch(), $actual, $id.' styled markup');
            if (!$ansi) {
                self::assertSame($txt, $actual, $id.' exact TXT');
            }
        }
    }

    /** @return iterable<string, array{int, string, string, bool}> */
    public static function matrix(): iterable
    {
        foreach ([52, 60, 84, 90, 110] as $width) {
            foreach (['success', 'conflict', 'multiple'] as $scenario) {
                foreach (['default', 'verbose', 'all', 'focus2', 'couplings'] as $mode) {
                    if ('focus2' === $mode && 'multiple' !== $scenario) {
                        continue;
                    }
                    foreach ([false, true] as $ansi) {
                        yield $width.'-'.$scenario.'-'.$mode.'-'.(int) $ansi => [$width, $scenario, $mode, $ansi];
                    }
                }
            }
        }
    }

    #[DataProvider('matrix')]
    public function testMatchesLivePrototypeWithActualSymfonyAcrossAllWidthsAndModes(int $width, string $scenario, string $mode, bool $ansi): void
    {
        $data = \SillbeamPrototype\Scenarios::get($scenario);
        // Coupling content in the prototype is intentionally hardcoded; supply it as test data only.
        $data['couplings'] = [['relation' => 'Admin → App\\Entity\\AuditLog', 'summary' => 'Admin references application code outside its module.', 'references' => [['file' => 'src/Module/Admin/Service/AuditWriter.php', 'line' => 21]]]];
        $reference = new BufferedOutput(decorated: $ansi);
        $actual = new BufferedOutput(decorated: $ansi);
        $verbose = 'verbose' === $mode;
        $all = 'all' === $mode;
        $issue = 'focus2' === $mode ? 2 : null;
        $couplings = 'couplings' === $mode;
        (new \SillbeamPrototype\ArchitectureRenderer($reference, $width, $verbose, $all, $issue, $couplings))->render($data);
        (new ArchitectureRenderer($actual, $width, $verbose, $all, $issue, $couplings))->render($data);
        self::assertSame($reference->fetch(), $actual->fetch());
    }

    public function testLongUnicodeUntrustedContentIsSafeAndFitsTheTerminal(): void
    {
        $scenario = \SillbeamPrototype\Scenarios::get('conflict');
        $value = str_repeat('界é👩‍💻', 30).' <error>literal</error> '."\033[2J\033]52;c;YXR0YWNr\007\r\x08";
        foreach (['title', 'summary', 'relation', 'caution', 'detail'] as $key) {
            $scenario['issues'][0][$key] = $value;
        }
        $scenario['issues'][] = $scenario['issues'][0];
        foreach ([52, 60, 84, 90, 110] as $width) {
            foreach ([false, true] as $ansi) {
                $output = new BufferedOutput(decorated: $ansi);
                (new ArchitectureRenderer($output, $width, true))->render($scenario);
                $text = preg_replace('/\x1B\[[0-9;]*m/', '', $output->fetch()) ?? '';
                self::assertStringContainsString('<error>literal</error>', $text);
                self::assertDoesNotMatchRegularExpression('/[\x00-\x08\x0B-\x1F\x7F]/', $text);
                foreach (explode("\n", $text) as $line) {
                    self::assertLessThanOrEqual(min(90, $width), Helper::width($line), $line);
                }
            }
        }
    }
}
